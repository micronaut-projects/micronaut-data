  /**
   * Build the positional parameter array used by JSON criteria encoding ({@code "$mn_qp:<index>"}).
   *
   * <p>For simple methods, {@link PreparedQuery#getParameterArray()} already matches the JSON
   * placeholder indices. For more complex bindings (for example {@link EmbeddedId}), Micronaut Data
   * provides a {@link PreparedQuery#getQueryBindings()} list that includes binding paths used to
   * extract individual placeholder values from a single method argument.
   */
  private Object[] buildJsonParameterValues(@NonNull final PreparedQuery<?, ?> q) {
    Object[] methodParams = q.getParameterArray();
    List<QueryParameterBinding> bindings = q.getQueryBindings();
    if (bindings == null || bindings.isEmpty()) {
      return methodParams;
    }
    Object[] values = new Object[bindings.size()];
    for (int i = 0; i < bindings.size(); i++) {
      values[i] = resolveJsonBindingValue(bindings.get(i), methodParams);
    }
    return values;
  }

  private Object resolveJsonBindingValue(
      @NonNull final QueryParameterBinding binding, final Object[] methodParams) {
    if (binding.getValue() != null) {
      return toFilterValue(binding.getValue());
    }
    int idx = binding.getParameterIndex();
    Object base = (methodParams != null && idx >= 0 && idx < methodParams.length) ? methodParams[idx] : null;
    String[] path = binding.getParameterBindingPath();
    if (path == null || path.length == 0) {
      path = binding.getPropertyPath();
    }
    if (path == null || path.length == 0) {
      return toFilterValue(base);
    }

    Object current = base;
    boolean conversionFailed = false;
    for (String segment : path) {
      if (current == null) {
        break;
      }
      if (current instanceof Map<?, ?> m) {
        current = m.get(segment);
      } else if (current instanceof Document d) {
        current = d.get(segment);
      } else {
        try {
          Document doc = (Document) nitriteMapper.tryConvert(current, Document.class);
          current = doc.get(segment);
        } catch (Exception ignored) {
          conversionFailed = true;
          break;
        }
      }
    }
    // Some query bindings include a property path (e.g. "id") even when the method parameter
    // already represents that scalar value. If we cannot traverse the path (because the parameter
    // isn't an object we can convert to a Document), fall back to the raw parameter value.
    return conversionFailed ? toFilterValue(base) : toFilterValue(current);
  }

  private Object[] ensureJsonParamsForFilter(
      @NonNull final Map<String, Object> filterMap,
      @NonNull final Object[] methodParams,
      final Object[] jsonParams) {
    int maxIdx = findMaxPlaceholderIndex(filterMap);
    if (maxIdx < 0) {
      return jsonParams;
    }
    Object[] out = jsonParams == null ? new Object[0] : jsonParams;
    if (out.length <= maxIdx) {
      out = Arrays.copyOf(out, maxIdx + 1);
    }
    fillMissingParamsFromFilter(filterMap, methodParams, out);
    return out;
  }

  private int findMaxPlaceholderIndex(final Map<String, Object> filterMap) {
    int max = -1;
    for (Map.Entry<String, Object> entry : filterMap.entrySet()) {
      Object value = entry.getValue();
      if (value instanceof Map<?, ?> m) {
        // Recurse for logical operators
        String key = entry.getKey();
        if ("$and".equals(key) || "$or".equals(key)) {
          if (value instanceof List<?> list) {
            for (Object item : list) {
              if (item instanceof Map<?, ?> im) {
                max = Math.max(max, findMaxPlaceholderIndex((Map<String, Object>) im));
              }
            }
          }
          continue;
        }
        // Operator maps
        for (Object opVal : m.values()) {
          Integer idx = extractPlaceholderIndex(opVal);
          if (idx != null) {
            max = Math.max(max, idx);
          }
        }
      } else {
        Integer idx = extractPlaceholderIndex(value);
        if (idx != null) {
          max = Math.max(max, idx);
        }
      }
    }
    return max;
  }

  private void fillMissingParamsFromFilter(
      final Map<String, Object> filterMap, final Object[] methodParams, final Object[] out) {
    for (Map.Entry<String, Object> entry : filterMap.entrySet()) {
      String key = entry.getKey();
      Object value = entry.getValue();
      if ("$and".equals(key) || "$or".equals(key)) {
        if (value instanceof List<?> list) {
          for (Object item : list) {
            if (item instanceof Map<?, ?> im) {
              fillMissingParamsFromFilter((Map<String, Object>) im, methodParams, out);
            }
          }
        }
        continue;
      }
      if (value instanceof Map<?, ?> ops) {
        for (Object opVal : ops.values()) {
          Integer idx = extractPlaceholderIndex(opVal);
          if (idx != null && idx >= 0 && idx < out.length && out[idx] == null) {
            out[idx] = extractPropertyFromSingleArg(methodParams, key);
          }
        }
      } else {
        Integer idx = extractPlaceholderIndex(value);
        if (idx != null && idx >= 0 && idx < out.length && out[idx] == null) {
          out[idx] = extractPropertyFromSingleArg(methodParams, key);
        }
      }
    }
  }

  private Integer extractPlaceholderIndex(final Object value) {
    if (value instanceof String s && s.startsWith("$mn_qp:")) {
      try {
        return Integer.parseInt(s.substring(7));
      } catch (NumberFormatException ignored) {
        return null;
      }
    }
    if (value instanceof Map<?, ?> vm
        && vm.size() == 1
        && vm.containsKey("$mn_qp")
        && vm.get("$mn_qp") instanceof Integer idx) {
      return idx;
    }
    return null;
  }

  private Object extractPropertyFromSingleArg(final Object[] methodParams, final String property) {
    if (methodParams == null || methodParams.length != 1 || methodParams[0] == null) {
      return null;
    }
    Object base = methodParams[0];
    try {
      Document doc = (Document) nitriteMapper.tryConvert(base, Document.class);
      return toFilterValue(doc.get(property));
    } catch (Exception ignored) {
      return null;
    }
  }

  /**
   * Build a Nitrite {@link Filter} from a {@link PreparedQuery}.
   *
   * <p>The query may be:
   *
   * <ul>
   *   <li>a JSON filter produced by {@code NitriteQueryBuilder}</li>
   *   <li>a SQL-like SELECT/DELETE generated by the document processor</li>
   * </ul>
   *
   * <p>JSON filters typically use {@code "$mn_qp:<index>"} placeholders resolved from the prepared
   * query parameter array.
   */
  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter buildFilterFromPreparedQuery(final PreparedQuery<?, ?> q) {
    String queryString = q.getQuery().trim();
    LOG.debug("buildFilterFromPreparedQuery query='{}' params={}", queryString, q.getParameterArray());
    if (queryString.isEmpty()) {
      return Filter.ALL;
    }

    Object[] params = q.getParameterArray();
    Object[] jsonParams = buildJsonParameterValues(q);
    Map<String, Object> namedParameters = buildNamedParameterValues(q);

    // Check for JSON filter generated by NitriteQueryBuilder (usually starts with { )
    if (queryString.startsWith("{")) {
      try {
        Object filterObj = parseJson(queryString);
        if (filterObj instanceof Map m) {
          // If it's an update query with $set, we still want the filter part
          Object[] effectiveParams =
              ensureJsonParamsForFilter((Map<String, Object>) m, params, jsonParams);
          return buildFilterFromJson((Map<String, Object>) m, effectiveParams, namedParameters);
        }
      } catch (Exception ignored) {
        // Fall through to SQL parsing
      }
    }

    // Fallback to SQL-like statement from document processor
    String upper = queryString.toUpperCase();
    Filter filter;
    if (upper.startsWith("DELETE")) {
      filter = parseFilterFromDeleteStatement(queryString, params);
    } else if (upper.startsWith("SELECT")) {
      filter = parseFilterFromSelectStatement(queryString, params);
    } else {
      throw new IllegalStateException(
          "Unsupported query format. Expected JSON filter or SELECT/DELETE statement, got: "
              + queryString);
    }
    LOG.debug("buildFilterFromPreparedQuery returning filter={}", filter);
    return filter;
  }

  /**
   * Parse filter from DELETE statement generated by micronaut-data-document-processor. Format:
   * DELETE entity AS alias WHERE condition
   */
  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter parseFilterFromDeleteStatement(final String sql, final Object[] params) {
    int whereIdx = sql.toUpperCase().indexOf(" WHERE ");
    if (whereIdx < 0) {
      return Filter.ALL;
    }
    String where = sql.substring(whereIdx + 7);
    // Trim ORDER BY if present (consistent with parseFilterFromSelectStatement)
    int orderByIdx = where.toUpperCase().indexOf(" ORDER BY");
    if (orderByIdx >= 0) {
      where = where.substring(0, orderByIdx);
    }
    return parseWhereClause(where, params);
  }

  /**
   * Parse filter from SELECT statement generated by micronaut-data-document-processor. Format:
   * SELECT alias FROM entity AS alias WHERE (condition)
   */
  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter parseFilterFromSelectStatement(final String sql, final Object[] params) {
    int whereIdx = sql.toUpperCase().indexOf(" WHERE ");
    if (whereIdx < 0) {
      return Filter.ALL;
    }
    String where = sql.substring(whereIdx + 7);
    // Remove ORDER BY if present
    int orderByIdx = where.toUpperCase().indexOf(" ORDER BY");
    if (orderByIdx >= 0) {
      where = where.substring(0, orderByIdx);
    }
    // Remove trailing parenthesis
    where = where.trim();
    if (where.startsWith("(") && where.endsWith(")")) {
      where = where.substring(1, where.length() - 1);
    }
    return parseWhereClause(where, params);
  }

  /** Parse WHERE clause conditions into Filter. */
  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter parseWhereClause(String where, final Object[] params) {
    List<Filter> filters = new ArrayList<>();

    // Special case: isEmpty pattern generated by document processor for findByXIsEmpty()
    // Pattern: (event_.payload IS NULL OR event_.payload = '')
    // We detect this and convert to $empty: true
    Matcher mEmpty =
        Pattern.compile(
                "\\(\\w+\\.(\\w+)\\s+IS\\s+NULL\\s+OR\\s+\\w+\\.\\1\\s*=\\s*''\\)",
                Pattern.CASE_INSENSITIVE)
            .matcher(where);
    if (!mEmpty.find()) {
      // Try without outer parentheses
      mEmpty =
          Pattern.compile(
                  "\\w+\\.(\\w+)\\s+IS\\s+NULL\\s+OR\\s+\\w+\\.\\1\\s*=\\s*''",
                  Pattern.CASE_INSENSITIVE)
              .matcher(where);
    }
    mEmpty.reset();
    while (mEmpty.find()) {
      String field = normalizeFieldName(mEmpty.group(1));
      filters.add(buildFieldFilter(field, Map.of("$empty", true), params));
      where = where.substring(0, mEmpty.start()) + "PROCESSED" + where.substring(mEmpty.end());
      mEmpty =
          Pattern.compile(
                  "\\w+\\.(\\w+)\\s+IS\\s+NULL\\s+OR\\s+\\w+\\.\\1\\s*=\\s*''",
                  Pattern.CASE_INSENSITIVE)
              .matcher(where);
    }

    // Pattern: alias.field = :pN
    Matcher m = SQL_COMPARISON.matcher(where);

    while (m.find()) {
      String field = normalizeFieldName(m.group(1));
      String op = m.group(2);
      String pname = m.group(3);
      Object rawVal = resolveParam(pname, params);
      Object val = toFilterValue(rawVal);

      String filterOp =
          switch (op) {
            case "=" -> "$eq";
            case "!=", "<>" -> "$ne";
            case ">" -> "$gt";
            case ">=" -> "$gte";
            case "<" -> "$lt";
            case "<=" -> "$lte";
            default -> "$eq";
          };

      filters.add(buildFieldFilter(field, Map.of(filterOp, val), params));
    }

    // IS NOT NULL pattern
    m = SQL_IS_NOT_NULL.matcher(where);
    while (m.find()) {
      filters.add(
          buildFieldFilter(normalizeFieldName(m.group(1)), Map.of("$notNull", true), params));
    }

    // IS NULL pattern
    m = SQL_IS_NULL.matcher(where);
    while (m.find()) {
      filters.add(buildFieldFilter(normalizeFieldName(m.group(1)), Map.of("$null", true), params));
    }

    // LIKE CONCAT pattern
    m = SQL_LIKE_CONCAT.matcher(where);
    while (m.find()) {
      String field = normalizeFieldName(m.group(1));
      String concatArgs = m.group(2);
      String pname = extractParamName(concatArgs);
      if (pname != null) {
        Object val = resolveParam(pname, params);
        if (val != null) {
          String[] parts = concatArgs.split(",\\s*");
          boolean prefixWild = parts[0].contains("%");
          boolean suffixWild = parts[parts.length - 1].contains("%");
          String regex;
          if (prefixWild && suffixWild) {
            regex = ".*" + Pattern.quote(val.toString()) + ".*";
          } else if (prefixWild) {
            regex = ".*" + Pattern.quote(val.toString());
          } else if (suffixWild) {
            regex = Pattern.quote(val.toString()) + ".*";
          } else {
            regex = Pattern.quote(val.toString());
          }
          filters.add(buildFieldFilter(field, Map.of("$regex", regex), params));
        }
      }
    }

    // Literal boolean: alias.field = true / alias.field = false
    m = SQL_LITERAL_BOOL.matcher(where);
    while (m.find()) {
      String field = normalizeFieldName(m.group(1));
      String op = m.group(2);
      boolean val = "true".equalsIgnoreCase(m.group(3));
      String filterOp = (op.equals("!=") || op.equals("<>")) ? "$ne" : "$eq";
      filters.add(buildFieldFilter(field, Map.of(filterOp, val), params));
    }

    // Empty string literal: alias.field = ''
    m = SQL_LITERAL_EMPTY_STR.matcher(where);
    while (m.find()) {
      filters.add(buildFieldFilter(normalizeFieldName(m.group(1)), Map.of("$eq", ""), params));
    }

    if (filters.isEmpty()) {
      return Filter.ALL;
    }
    if (filters.size() == 1) {
      return filters.get(0);
    }
    return Filter.and(filters.toArray(new Filter[0]));
  }

  /** Extract the :pN parameter name from a CONCAT argument list. */
  private String extractParamName(final String concatArgs) {
    for (String part : concatArgs.split(",\\s*")) {
      String t = part.trim();
      if (t.startsWith(":")) {
        return t.substring(1);
      }
    }
    return null;
  }

  /** Resolve :pN (1-indexed) to the actual method argument. */
  private Object resolveParam(final String pname, final Object[] params) {
    try {
      if (pname.startsWith("p")) {
        int idx = Integer.parseInt(pname.substring(1)) - 1;
        if (params != null && idx >= 0 && idx < params.length) {
          return params[idx];
        }
      }
    } catch (NumberFormatException ignored) {
    }
    return null;
  }

  /**
   * Parses a small JSON subset into a {@link Map}/{@link List} structure.
   *
   * <p>This is intentionally minimal (used only for the query strings produced by the Nitrite query
   * builder and for user-authored JSON {@code @Query} methods). One important edge case: JSON
   * placeholders like {@code :name} must remain intact; the parser must not treat the placeholder’s
   * leading {@code ':'} as the key/value separator.
   */
  private Object parseJson(final String jsonStr) {
    String json = jsonStr.trim();
    if (json.equals("{}")) {
      return Map.of();
    }
    if (json.startsWith("{")) {
      return parseJsonObject(json);
    }
    if (json.startsWith("[")) {
      return parseJsonArray(json);
    }
    throw new IllegalArgumentException("Invalid JSON: " + json);
  }

  private Map<String, Object> parseJsonObject(String json) {
    Map<String, Object> result = new LinkedHashMap<>();
    json = json.trim();
    if (json.equals("{}")) {
      return result;
    }

    // Remove outer braces
    json = json.substring(1, json.length() - 1).trim();

    int i = 0;
    while (i < json.length()) {
      // Skip whitespace
      while (i < json.length() && Character.isWhitespace(json.charAt(i))) {
        i++;
      }
      if (i >= json.length()) {
        break;
      }

      // Parse key
      if (json.charAt(i) != '"') {
        throw new IllegalArgumentException("Expected '\"' at " + i);
      }
      i++;
      int keyStart = i;
      while (i < json.length() && json.charAt(i) != '"') {
        if (json.charAt(i) == '\\') {
          i++;
        }
        i++;
      }
      String key = json.substring(keyStart, i);
      i++; // skip closing quote

      // Skip the key/value separator ':' (but don't consume placeholder ':' that may start the value,
      // e.g. {"title": :title}).
      while (i < json.length() && Character.isWhitespace(json.charAt(i))) {
        i++;
      }
      if (i < json.length() && json.charAt(i) == ':') {
        i++;
      }
      while (i < json.length() && Character.isWhitespace(json.charAt(i))) {
        i++;
      }

      // Parse value
      Object value;
      if (i >= json.length()) {
        break;
      }
      char c = json.charAt(i);
      if (c == '"') {
        i++;
        StringBuilder sb = new StringBuilder();
        while (i < json.length() && json.charAt(i) != '"') {
          if (json.charAt(i) == '\\') {
            i++;
            if (i < json.length()) {
              char escaped = json.charAt(i);
              switch (escaped) {
                case '"' -> sb.append('"');
                case '\\' -> sb.append('\\');
                case 'n' -> sb.append('\n');
                case 'r' -> sb.append('\r');
                case 't' -> sb.append('\t');
                default -> sb.append(escaped);
              }
            }
          } else {
            sb.append(json.charAt(i));
          }
          i++;
        }
        value = sb.toString();
        i++; // skip closing quote
      } else if (c == '{') {
        int start = i;
        int depth = 1;
        i++;
        while (i < json.length() && depth > 0) {
          if (json.charAt(i) == '{') {
            depth++;
          }
          if (json.charAt(i) == '}') {
            depth--;
          }
          i++;
        }
        value = parseJsonObject(json.substring(start, i));
      } else if (c == '[') {
        int start = i;
        int depth = 1;
        i++;
        while (i < json.length() && depth > 0) {
          if (json.charAt(i) == '[') {
            depth++;
          }
          if (json.charAt(i) == ']') {
            depth--;
          }
          i++;
        }
        value = parseJsonArray(json.substring(start, i));
      } else if (c == 't' || c == 'f') {
        // boolean or :pname placeholder
        int start = i;
        while (i < json.length() && (Character.isLetter(json.charAt(i)) || json.charAt(i) == ':')) {
          i++;
        }
        String s = json.substring(start, i);
        if (s.startsWith(":") || s.startsWith("$mn_qp:")) {
            value = s;
        } else if (s.equals("true") || s.equals("false")) {
            value = Boolean.parseBoolean(s);
        } else {
            value = s;
        }
      } else if (c == ':') {
        // :pname placeholder starting with :
        int start = i;
        while (i < json.length() && (Character.isLetterOrDigit(json.charAt(i)) || json.charAt(i) == ':')) {
          i++;
        }
        value = json.substring(start, i);
      } else if (c == '$') {
        // $mn_qp: placeholder starting with $
        int start = i;
        while (i < json.length() && (Character.isLetterOrDigit(json.charAt(i)) || json.charAt(i) == ':' || json.charAt(i) == '$' || json.charAt(i) == '_')) {
          i++;
        }
        value = json.substring(start, i);
      } else if (c == 'n') {
        // null
        i += 4;
        value = null;
      } else {
        // number
        int start = i;
        while (i < json.length()
            && (Character.isDigit(json.charAt(i))
                || json.charAt(i) == '.'
                || json.charAt(i) == '-')) {
          i++;
        }
        String numStr = json.substring(start, i).trim();
        if (numStr.startsWith("$mn_qp:")) {
          value = numStr;
        } else if (numStr.contains(".")) {
          value = Double.parseDouble(numStr);
        } else {
          try {
            value = Integer.parseInt(numStr);
          } catch (NumberFormatException e) {
            value = numStr;
          }
        }
      }

      result.put(key, value);

      // Skip comma
      while (i < json.length()
          && (Character.isWhitespace(json.charAt(i)) || json.charAt(i) == ',')) {
        i++;
      }
    }

    return result;
  }

  private List<Object> parseJsonArray(String json) {
    List<Object> result = new ArrayList<>();
    json = json.trim();
    if (json.equals("[]")) {
      return result;
    }

    // Remove outer brackets
    json = json.substring(1, json.length() - 1).trim();

    int i = 0;
    while (i < json.length()) {
      // Skip whitespace and commas
      while (i < json.length()
          && (Character.isWhitespace(json.charAt(i)) || json.charAt(i) == ',')) {
        i++;
      }
      if (i >= json.length()) {
        break;
      }

      char c = json.charAt(i);
      Object value;
      if (c == '"') {
        i++;
        StringBuilder sb = new StringBuilder();
        while (i < json.length() && json.charAt(i) != '"') {
          if (json.charAt(i) == '\\') {
            i++;
            if (i < json.length()) {
              char escaped = json.charAt(i);
              switch (escaped) {
                case '"' -> sb.append('"');
                case '\\' -> sb.append('\\');
                case 'n' -> sb.append('\n');
                case 'r' -> sb.append('\r');
                case 't' -> sb.append('\t');
                default -> sb.append(escaped);
              }
            }
          } else {
            sb.append(json.charAt(i));
          }
          i++;
        }
        value = sb.toString();
        i++; // skip closing quote
      } else if (c == '{') {
        int start = i;
        int depth = 1;
        i++;
        while (i < json.length() && depth > 0) {
          if (json.charAt(i) == '{') {
            depth++;
          }
          if (json.charAt(i) == '}') {
            depth--;
          }
          i++;
        }
        value = parseJsonObject(json.substring(start, i));
      } else if (c == '[') {
        int start = i;
        int depth = 1;
        i++;
        while (i < json.length() && depth > 0) {
          if (json.charAt(i) == '[') {
            depth++;
          }
          if (json.charAt(i) == ']') {
            depth--;
          }
          i++;
        }
        value = parseJsonArray(json.substring(start, i));
      } else {
        int start = i;
        while (i < json.length()
            && (Character.isDigit(json.charAt(i))
                || json.charAt(i) == '.'
                || json.charAt(i) == '-')) {
          i++;
        }
        String str = json.substring(start, i).trim();
        if (str.startsWith("$mn_qp:")) {
          value = str;
        } else if (str.equals("true")) {
          value = true;
        } else if (str.equals("false")) {
          value = false;
        } else if (str.equals("null")) {
          value = null;
        } else if (str.contains(".")) {
          value = Double.parseDouble(str);
        } else {
          try {
            value = Integer.parseInt(str);
          } catch (NumberFormatException e) {
            value = str;
          }
        }
      }

      result.add(value);
    }

    return result;
  }

  /** Builds a Nitrite Filter from a parsed JSON filter object. */
  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter buildFilterFromJson(
      final Map<String, Object> filterObj,
      final Object[] params,
      final Map<String, Object> namedParameters) {
    if (filterObj.isEmpty()) {
      return Filter.ALL;
    }

    List<Filter> filters = new ArrayList<>();

    for (Map.Entry<String, Object> entry : filterObj.entrySet()) {
      String key = entry.getKey();
      Object value = entry.getValue();

      if (key.equals("$sort") || key.equals("$set") || key.equals("$limit") || key.equals("$skip") || key.equals("$count")) {
        continue;
      }

      if (key.equals("$and")) {
        if (value instanceof List<?> list) {
          List<Filter> andFilters = new ArrayList<>();
          for (Object item : list) {
            if (item instanceof Map<?, ?> m) {
              Filter f = buildFilterFromJson((Map<String, Object>) m, params, namedParameters);
              if (f != null && f != Filter.ALL) {
                andFilters.add(f);
              }
            }
          }
          if (!andFilters.isEmpty()) {
            filters.add(Filter.and(andFilters.toArray(new Filter[0])));
          }
        }
      } else if (key.equals("$or")) {
        if (value instanceof List<?> list) {
          List<Filter> orFilters = new ArrayList<>();
          for (Object item : list) {
            if (item instanceof Map<?, ?> m) {
              Filter f = buildFilterFromJson((Map<String, Object>) m, params, namedParameters);
              if (f != null && f != Filter.ALL) {
                orFilters.add(f);
              }
            }
          }
          if (!orFilters.isEmpty()) {
            filters.add(Filter.or(orFilters.toArray(new Filter[0])));
          }
        }
      } else {
        // Plain field filter
        if (value instanceof Map<?, ?> m) {
          Filter f = buildFieldFilter(key, (Map<String, Object>) m, params, namedParameters);
          if (f != null && f != Filter.ALL) {
            filters.add(f);
          }
        } else {
          // Simple equality: { "field": "value" }
          Filter f =
              buildFieldFilter(
                  key, Collections.singletonMap("$eq", value), params, namedParameters);
          if (f != null && f != Filter.ALL) {
            filters.add(f);
          }
        }
      }
    }

    Filter result;
    if (filters.isEmpty()) {
      result = Filter.ALL;
    } else if (filters.size() == 1) {
      result = filters.get(0);
    } else {
      result = Filter.and(filters.toArray(new Filter[0]));
    }
    LOG.debug("buildFilterFromJson returning filter={}", result);
    return result;
  }

  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter buildFieldFilter(
      final String field, final Map<String, Object> operators, final Object[] params) {
    return buildFieldFilter(field, operators, params, Collections.emptyMap());
  }

  @SuppressWarnings({"unchecked", "rawtypes"})
  private Filter buildFieldFilter(
      final String field,
      final Map<String, Object> operators,
      final Object[] params,
      final Map<String, Object> namedParameters) {
    List<Filter> fieldFilters = new ArrayList<>();

    for (Map.Entry<String, Object> opEntry : operators.entrySet()) {
      String op = opEntry.getKey();
      Object value = opEntry.getValue();

      // Resolve parameter placeholders
      if (value instanceof String s && s.startsWith("$mn_qp:")) {
        int paramIdx = Integer.parseInt(s.substring(7));
        if (params != null && paramIdx >= 0 && paramIdx < params.length) {
          value = toNitriteFilterValue(params[paramIdx]);
        }
      } else if (value instanceof String s && s.startsWith(":")) {
        String name = s.substring(1);
        if (namedParameters.containsKey(name)) {
          value = toNitriteFilterValue(namedParameters.get(name));
        }
      }
      if (value instanceof Map<?, ?> vm
          && vm.size() == 1
          && vm.containsKey("$mn_qp")
          && vm.get("$mn_qp") instanceof Integer paramIdx) {
        if (params != null && paramIdx >= 0 && paramIdx < params.length) {
          value = toNitriteFilterValue(params[paramIdx]);
        }
      }

      Object finalValue = toNitriteFilterValue(value);

      Filter f =
          switch (op) {
            case "$eq" -> eqWithNumericCoercion(field, finalValue);
            case "$ne" -> FluentFilter.where(field).notEq(finalValue);
            case "$gt" -> {
                if (finalValue instanceof Comparable c) {
                    yield FluentFilter.where(field).gt(c);
                }
                yield Filter.ALL;
            }
            case "$gte" -> {
                if (finalValue instanceof Comparable c) {
                    yield FluentFilter.where(field).gte(c);
                }
                yield Filter.ALL;
            }
            case "$lt" -> {
                if (finalValue instanceof Comparable c) {
                    yield FluentFilter.where(field).lt(c);
                }
                yield Filter.ALL;
            }
            case "$lte" -> {
                if (finalValue instanceof Comparable c) {
                    yield FluentFilter.where(field).lte(c);
                }
                yield Filter.ALL;
            }
            case "$in" -> {
              if (finalValue instanceof Collection<?> coll) {
                List<Comparable> resolvedValues = new ArrayList<>();
                for (Object item : coll) {
                    Object resolved = item;
                    if (item instanceof String s && s.startsWith("$mn_qp:")) {
                        int paramIdx = Integer.parseInt(s.substring(7));
                        if (params != null && paramIdx >= 0 && paramIdx < params.length) {
                            resolved = toNitriteFilterValue(params[paramIdx]);
                        }
                    } else if (item instanceof String s && s.startsWith(":")) {
                        String name = s.substring(1);
                        if (namedParameters.containsKey(name)) {
                            resolved = toNitriteFilterValue(namedParameters.get(name));
                        }
                    }
                    if (resolved instanceof Comparable c) {
                        resolvedValues.add(c);
                    }
                }
                yield FluentFilter.where(field).in(resolvedValues.toArray(new Comparable[0]));
              } else {
                // Single value - treat as single-element list
                yield FluentFilter.where(field).eq(finalValue);
              }
            }
            case "$nin" -> {
              if (finalValue instanceof Collection<?> coll) {
                List<Comparable> resolvedValues = new ArrayList<>();
                for (Object item : coll) {
                    Object resolved = item;
                    if (item instanceof String s && s.startsWith("$mn_qp:")) {
                        int paramIdx = Integer.parseInt(s.substring(7));
                        if (params != null && paramIdx >= 0 && paramIdx < params.length) {
                            resolved = toNitriteFilterValue(params[paramIdx]);
                        }
                    } else if (item instanceof String s && s.startsWith(":")) {
                        String name = s.substring(1);
                        if (namedParameters.containsKey(name)) {
                            resolved = toNitriteFilterValue(namedParameters.get(name));
                        }
                    }
                    if (resolved instanceof Comparable c) {
                        resolvedValues.add(c);
                    }
                }
                yield FluentFilter.where(field).notIn(resolvedValues.toArray(new Comparable[0]));
              } else {
                // Single value
                yield FluentFilter.where(field).notEq(finalValue);
              }
            }
            case "$null" ->
                finalValue.equals(true) ? FluentFilter.where(field).eq(null) : Filter.ALL;
            case "$notNull" ->
                finalValue.equals(true) ? FluentFilter.where(field).notEq(null) : Filter.ALL;
            case "$between" -> {
              if (finalValue instanceof List<?> list && list.size() == 2) {
                Object v1 = list.get(0);
                Object v2 = list.get(1);
                if (v1 instanceof String s && s.startsWith("$mn_qp:")) {
                    int paramIdx = Integer.parseInt(s.substring(7));
                    if (params != null && paramIdx >= 0 && paramIdx < params.length) {
                        v1 = toFilterValue(params[paramIdx]);
                    }
                }
                if (v2 instanceof String s && s.startsWith("$mn_qp:")) {
                    int paramIdx = Integer.parseInt(s.substring(7));
                    if (params != null && paramIdx >= 0 && paramIdx < params.length) {
                        v2 = toFilterValue(params[paramIdx]);
                    }
                }
                yield FluentFilter.where(field)
                    .between((Comparable) v1, (Comparable) v2);
              }
              yield Filter.ALL;
            }
            case "$regex" -> FluentFilter.where(field).regex(finalValue.toString());
            case "$not" -> {
              // Negation of a filter
              if (finalValue instanceof Map) {
                Filter innerFilter =
                    buildFieldFilter(field, (Map<String, Object>) finalValue, params, namedParameters);
                yield innerFilter != Filter.ALL ? innerFilter.not() : Filter.ALL;
              }
              yield Filter.ALL;
            }
            case "$exists" ->
                finalValue.equals(true)
                    ? FluentFilter.where(field).notEq(null)
                    : FluentFilter.where(field).eq(null);
            case "$size" -> {
              // Size operator - Nitrite doesn't have direct size support, use document field size
              if (finalValue instanceof Map) {
                Map<?, ?> sizeCriteria = (Map<?, ?>) finalValue;
                // For now, handle simple equality
                Object sizeValue = sizeCriteria.get("$eq");
                if (sizeValue != null) {
                  // Note: This requires the document to have a pre-computed size field
                  // Full implementation would need custom filter
                  yield FluentFilter.where(field + "_size").eq(sizeValue);
                }
              }
              yield Filter.ALL;
            }
            case "$empty" ->
                finalValue.equals(true)
                    ? Filter.or(
                        FluentFilter.where(field).eq(""), FluentFilter.where(field).eq(null))
                    : Filter.and(
                        FluentFilter.where(field).notEq(""), FluentFilter.where(field).notEq(null));
            case "$true" -> FluentFilter.where(field).eq(true);
            case "$false" -> FluentFilter.where(field).eq(false);
            case "$arrayContains" -> {
              // For array fields, check if array contains the value
              if (finalValue instanceof Collection) {
                Collection<?> vals = (Collection<?>) finalValue;
                yield FluentFilter.where(field).in(vals.toArray(new Comparable[0]));
              }
              yield FluentFilter.where(field).eq(finalValue);
            }
            default -> FluentFilter.where(field).eq(finalValue);
          };

      if (f != null && f != Filter.ALL) {
        fieldFilters.add(f);
      }
    }

    if (fieldFilters.isEmpty()) {
      return Filter.ALL;
    }
    if (fieldFilters.size() == 1) {
      return fieldFilters.get(0);
    }
    return Filter.and(fieldFilters.toArray(new Filter[0]));
  }

