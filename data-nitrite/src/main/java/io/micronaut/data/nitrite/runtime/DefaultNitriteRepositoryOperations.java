  /**
   * Reorders the PreparedQuery parameter array to match SQL :p1, :p2, ... positions. For UPDATE SQL
   * the processor assigns :p1 to the SET field regardless of its method argument position, so we
   * use QueryParameterBinding.getParameterIndex() to get the correct method-arg index for each SQL
   * placeholder.
   */
  private Object[] reorderParamsForSql(final PreparedQuery<?, ?> q) {
    Object[] rawParams = q.getParameterArray();
    List<QueryParameterBinding> bindings = q.getQueryBindings();
    if (bindings == null || bindings.isEmpty() || rawParams == null) {
      return rawParams;
    }
    Object[] reordered = new Object[bindings.size()];
    for (QueryParameterBinding binding : bindings) {
      String name = binding.getName(); // "p1", "p2", ...
      int paramIdx = binding.getParameterIndex(); // index into rawParams
      if (name != null && name.startsWith("p")) {
        try {
          int sqlPos = Integer.parseInt(name.substring(1)) - 1; // "p1" -> 0
          if (sqlPos >= 0
              && sqlPos < reordered.length
              && paramIdx >= 0
              && paramIdx < rawParams.length) {
            reordered[sqlPos] = rawParams[paramIdx];
          }
        } catch (NumberFormatException ignored) {
        }
      }
    }
    return reordered;
  }

  public Optional<Number> executeUpdate(@NonNull final PreparedQuery<?, Number> q) {
    String query = q.getQuery();
    Object[] params = q.getParameterArray();
    Object[] jsonParams = buildJsonParameterValues(q);
    Map<String, Object> setFields;
    Filter filter;

    if (query.trim().startsWith("{")) {
      Map<String, Object> filterMap = (Map<String, Object>) parseJson(query);
      setFields = (Map<String, Object>) filterMap.get("$set");
      if (setFields == null) {
        setFields = Map.of();
      } else {
        // Bind parameters in setFields
        List<QueryParameterBinding> bindings = q.getQueryBindings();
        for (Map.Entry<String, Object> entry : setFields.entrySet()) {
          Object value = entry.getValue();
          if (value instanceof String s) {
              if (s.startsWith("$mn_qp:")) {
                int idx = Integer.parseInt(s.substring(7));
                if (idx >= 0 && idx < jsonParams.length) {
                  entry.setValue(toFilterValue(jsonParams[idx]));
                }
              } else if (s.startsWith(":")) {
                  String pname = s.substring(1);
                  for (QueryParameterBinding b : bindings) {
                      if (pname.equals(b.getName())) {
                          entry.setValue(toFilterValue(params[b.getParameterIndex()]));
                          break;
                      }
                  }
              }
          }
          if (value instanceof Map<?, ?> vm
              && vm.size() == 1
              && vm.containsKey("$mn_qp")
              && vm.get("$mn_qp") instanceof Integer paramIdx) {
            if (paramIdx >= 0 && paramIdx < jsonParams.length) {
              entry.setValue(toFilterValue(jsonParams[paramIdx]));
            }
          }
        }
      }
      Map<String, Object> namedParameters = buildNamedParameterValues(q);
      filter = buildFilterFromJson(filterMap, jsonParams, namedParameters);
    } else if (query.trim().toUpperCase().startsWith("UPDATE")) {
      Object[] sqlParams = reorderParamsForSql(q);
      setFields = parseSetClause(query, sqlParams);
      filter = parseFilterFromUpdateStatement(query, sqlParams);
    } else {
      throw new UnsupportedOperationException(
          "executeUpdate() called with non-UPDATE statement: " + query);
    }

    if (setFields.isEmpty()) {
      return Optional.of(0);
    }
    LOG.debug("executeUpdate filter={} setFields={} params={}", filter, setFields, params);
    NitriteCollection collection = getCollection(q.getRootEntity());

    // Nitrite updates are partial updates with the provided fields. Do not wrap in "$set" (Mongo-style),
    // otherwise the document will get a literal "$set" field and the target fields won't change.
    Document updateDoc = Document.createDocument();
    for (Map.Entry<String, Object> entry : setFields.entrySet()) {
      updateDoc.put(entry.getKey(), entry.getValue());
    }

    var result = collection.update(filter, updateDoc, UpdateOptions.updateOptions(false));
    int count = result.getAffectedCount();

    LOG.debug("executeUpdate updated {} documents", count);
    return Optional.of(count);
  }

  /**
   * Build a map for named parameters used by user-authored JSON {@code @Query} strings (e.g.
   * {@code {"title": :title}}).
   *
   * <p>This variant uses explicit binding metadata ({@link QueryParameterBinding}) when available.
   */
  private Map<String, Object> buildNamedParameterValues(
      final List<QueryParameterBinding> bindings, final Object[] params) {
    if (bindings == null || bindings.isEmpty() || params == null || params.length == 0) {
      return Collections.emptyMap();
    }
    Map<String, Object> result = new HashMap<>();
    for (QueryParameterBinding b : bindings) {
      String name = b.getName();
      int idx = b.getParameterIndex();
      if (name == null || idx < 0 || idx >= params.length) {
        continue;
      }
      result.put(name, toFilterValue(params[idx]));
    }
    return result;
  }

  /**
   * Build a map for named parameters used by user-authored JSON {@code @Query} strings (e.g.
   * {@code {"title": :title}}).
   *
   * <p>Prefer {@link PreparedQuery#getQueryBindings()} (explicit binding metadata). If bindings
   * don't include names, fall back to {@link PreparedQuery#getArguments()} argument names.
   */
  private Map<String, Object> buildNamedParameterValues(@NonNull final PreparedQuery<?, ?> q) {
    Object[] params = q.getParameterArray();
    Map<String, Object> byBindings = buildNamedParameterValues(q.getQueryBindings(), params);
    if (!byBindings.isEmpty()) {
      return byBindings;
    }
    if (params == null || params.length == 0) {
      return Collections.emptyMap();
    }
    Argument[] arguments = q.getArguments();
    if (arguments == null || arguments.length == 0) {
      return Collections.emptyMap();
    }
    int len = Math.min(arguments.length, params.length);
    Map<String, Object> fallback = new HashMap<>();
    for (int i = 0; i < len; i++) {
      String name = arguments[i].getName();
      if (name != null && !name.isEmpty()) {
        fallback.put(name, toFilterValue(params[i]));
      }
    }
    return fallback;
  }

  /**
   * Execute an update encoded as JSON (filter + {@code "$set"}).
   *
   * <p>This exists as a compatibility path for JSON {@code @Query} methods that encode updates using
   * a Mongo-style {@code "$set"} wrapper.
   */
  @SuppressWarnings({"unchecked", "rawtypes"})
  private int executeJsonUpdate(
      @NonNull final PreparedQuery<?, ?> q, @NonNull final Map<String, Object> queryMap) {
    Object[] params = q.getParameterArray();
    Object[] jsonParams = buildJsonParameterValues(q);
    Map<String, Object> namedParameters = buildNamedParameterValues(q);

    Object rawSet = queryMap.get("$set");
    if (!(rawSet instanceof Map<?, ?> setFields) || setFields.isEmpty()) {
      return 0;
    }

    // Filter is the query map minus $set (buildFilterFromJson already skips $set)
    Filter filter = buildFilterFromJson(queryMap, jsonParams, namedParameters);
    NitriteCollection collection = getCollection(q.getRootEntity());

    Document updateDoc = Document.createDocument();
    for (Map.Entry<?, ?> e : setFields.entrySet()) {
      Object key = e.getKey();
      if (!(key instanceof String fieldName)) {
        continue;
      }
      Object value = e.getValue();
      if (value instanceof String s && s.startsWith("$mn_qp:")) {
        int idx = Integer.parseInt(s.substring(7));
        if (idx >= 0 && idx < jsonParams.length) {
          value = toFilterValue(jsonParams[idx]);
        }
      } else if (value instanceof String s && s.startsWith(":")) {
        String name = s.substring(1);
        if (namedParameters.containsKey(name)) {
          value = namedParameters.get(name);
        }
      }
      updateDoc.put(fieldName, value);
    }

    var result = collection.update(filter, updateDoc, UpdateOptions.updateOptions(false));
    return result.getAffectedCount();
  }

  /** Parse SET clause from UPDATE SQL into a field→value map. */
  private Map<String, Object> parseSetClause(final String sql, final Object[] params) {
    int setIdx = sql.toUpperCase().indexOf(" SET ");
    int whereIdx = sql.toUpperCase().indexOf(" WHERE ");
    if (setIdx < 0) {
      return Map.of();
    }
    String setClause =
        whereIdx >= 0 ? sql.substring(setIdx + 5, whereIdx) : sql.substring(setIdx + 5);
    Map<String, Object> fields = new LinkedHashMap<>();
    Matcher m = SQL_SET_ASSIGNMENT.matcher(setClause);
    while (m.find()) {
      String field = m.group(1);
      String pname = m.group(2);
      Object val = resolveParam(pname, params);
      fields.put(field, val);
    }
    return fields;
  }

  /** Parse WHERE clause from UPDATE SQL into a Nitrite Filter. */
  private Filter parseFilterFromUpdateStatement(final String sql, final Object[] params) {
    int whereIdx = sql.toUpperCase().indexOf(" WHERE ");
    if (whereIdx < 0) {
      return Filter.ALL;
    }
    String where = sql.substring(whereIdx + 7).trim();
    if (where.startsWith("(") && where.endsWith(")")) {
      where = where.substring(1, where.length() - 1);
    }
    return parseWhereClause(where, params);
  }

  /**
   * Execute a prepared delete query and return affected count.
   *
   * <p>This method is invoked by Micronaut Data runtime for {@code @Query} delete operations and
   * for generated deletes (including implicit {@code CrudRepository} methods).
   *
   * @param q The prepared query
   * @return Optional affected count
   */
  public Optional<Number> executeDelete(@NonNull final PreparedQuery<?, Number> q) {
    Class<?> rootEntity = q.getRootEntity();
    NitriteCollection collection = getCollection(rootEntity);
    Filter filter = buildFilterFromPreparedQuery(q);
    var result = collection.remove(filter, false);
    return Optional.of(result.getAffectedCount());
  }

  /**
   * Execute a prepared query and return results as a list.
   *
   * @param q The prepared query
   * @return Results list
   * @param <R> result type
   */
  public <R> List<R> execute(@NonNull final PreparedQuery<?, R> q) {
    List<R> list = new ArrayList<>();
    findAll(q).forEach(list::add);
    return list;
  }

