  /** Get collection name from entity class. */
  private String getCollectionName(final Class<?> type) {
    MappedEntity mappedEntity = type.getAnnotation(MappedEntity.class);
    if (mappedEntity != null && !mappedEntity.value().isEmpty()) {
      return mappedEntity.value();
    }
    return type.getSimpleName();
  }

  /** Get Nitrite collection for entity type. */
  private NitriteCollection getCollection(final Class<?> type) {
    String name = getCollectionName(type);
    if (transactionHolder.isActive()) {
      // Nitrite transactions require the collection to pre-exist before the transaction started.
      // Touch the collection on the database first (idempotent: creates if absent).
      database.getCollection(name);
      return transactionHolder.get().getCollection(name);
    }
    return database.getCollection(name);
  }

  /** Convert entity to Nitrite Document. */
  private <T> Document toDocument(final T entity) {
    Document doc = (Document) nitriteMapper.tryConvert(entity, Document.class);
    // Entities with @JsonProperty("_id") cause Jackson to serialize the id as "_id".
    // Nitrite reserves "_id" for NitriteId — rename user's id to "id" to avoid InvalidIdException.
    Object reservedId = doc.get("_id");
    if (reservedId != null && !(reservedId instanceof NitriteId)) {
      doc.remove("_id");
      doc.put("id", toFilterValue(reservedId));
    }

    // EmbeddedId: document implementations can encode embedded-id fields as root attributes.
    // To support both encodings, store the embedded-id object under its property name *and* flatten
    // its component properties into top-level fields. If a component field name collides with the
    // wrapper property name, skip flattening that field.
    RuntimePersistentEntity<T> persistentEntity = getEntity((Class<T>) entity.getClass());
    RuntimePersistentProperty<T> idProperty = persistentEntity.getIdentity();
    if (idProperty != null && idProperty.isAnnotationPresent(EmbeddedId.class)) {
      Object embeddedId = idProperty.getProperty().get(entity);
      if (embeddedId != null) {
        try {
          Document idDoc = (Document) nitriteMapper.tryConvert(embeddedId, Document.class);
          doc.put(idProperty.getName(), idDoc);
          for (String field : idDoc.getFields()) {
            if (field.equals(idProperty.getName())) {
              continue;
            }
            doc.put(field, toFilterValue(idDoc.get(field)));
          }
        } catch (Exception ignored) {
          // Keep original mapping
        }
      }
    }
    return doc;
  }

  /** Convert Nitrite Document to entity. */
  @SuppressWarnings("unchecked")
  private <T> T fromDocument(final Document doc, final Class<T> type) {
    // Create a copy of the document using only user-visible fields (doc.getFields() excludes
    // Nitrite internals: "_id"/NitriteId, "_revision", "_modified", "_source").
    // This prevents entities with @JsonProperty("_id") from getting the NitriteId (a numeric long)
    // where they expect a UUID, which would cause ObjectMappingException.
    Document docCopy = Document.createDocument();
    for (String field : doc.getFields()) {
      docCopy.put(field, doc.get(field));
    }
    T entity;
    try {
      entity = (T) nitriteMapper.tryConvert(docCopy, type);
    } catch (Exception e) {
      // Jackson mapper can't always construct immutable embedded-id types from nested documents
      // (no default constructor / no JsonCreator). Retry without the wrapper field and rebuild the
      // embedded id from flattened top-level fields below.
      var idProp = getEntity(type).getIdentity();
      if (idProp != null && idProp.isAnnotationPresent(EmbeddedId.class)) {
        Document retryDoc = Document.createDocument();
        RuntimePersistentEntity<T> persistentEntity = getEntity(type);
        for (RuntimePersistentProperty<T> p : persistentEntity.getPersistentProperties()) {
          String name = p.getName();
          if (name.equals(idProp.getName())) {
            continue;
          }
          Object v = doc.get(name);
          if (v != null) {
            retryDoc.put(name, v);
          }
        }
        entity = (T) nitriteMapper.tryConvert(retryDoc, type);
      } else {
        throw e;
      }
    }
    // Post-process: entities with @JsonProperty("_id") have their id field mapped to "_id" key.
    // Since we stripped "_id" (NitriteId) from docCopy, Jackson left id=null. Restore from "id".
    var idProp = getEntity(type).getIdentity();
    if (idProp != null && idProp.getProperty().get(entity) == null) {
      Object storedId = doc.get("id");
      if (storedId != null) {
        idProp.getProperty().set(entity, convertIdValue(storedId, idProp.getType()));
      }
    }

    // EmbeddedId: reconstruct the embedded id object from flattened top-level fields.
    if (idProp != null
        && idProp.isAnnotationPresent(EmbeddedId.class)
        && idProp.getProperty().get(entity) == null) {
      try {
        Class<?> embeddedIdType = idProp.getType();
        BeanIntrospection<?> idIntrospection = BeanIntrospection.getIntrospection(embeddedIdType);
        Object embeddedId = null;

        // Prefer BeanIntrospection constructor instantiation for immutable embedded-id classes.
        Argument<?>[] ctorArgs = idIntrospection.getConstructorArguments();
        if (ctorArgs.length > 0) {
          Object[] values = new Object[ctorArgs.length];
          for (int i = 0; i < ctorArgs.length; i++) {
            String name = ctorArgs[i].getName();
            Optional<? extends BeanProperty<?, ?>> property = idIntrospection.getProperty(name);
            String storedName = property
                .flatMap(p -> p.getAnnotationMetadata()
                    .stringValue(MappedProperty.class)
                    .filter(v -> !v.isBlank()))
                .orElse(name);
            Object storedValue = doc.get(storedName);
            values[i] = conversionService.convertRequired(storedValue, ctorArgs[i]);
          }
          embeddedId = idIntrospection.instantiate(values);
        } else {
          // Mutable embedded-id (default constructor): set known bean properties from storage.
          embeddedId = idIntrospection.instantiate();
          for (BeanProperty<?, ?> property : idIntrospection.getBeanProperties()) {
            if (property.isReadOnly()) {
              continue;
            }
            String storedName = property.getAnnotationMetadata()
                .stringValue(MappedProperty.class)
                .filter(v -> !v.isBlank())
                .orElse(property.getName());
            Object storedValue = doc.get(storedName);
            if (storedValue != null) {
              @SuppressWarnings({"rawtypes", "unchecked"})
              BeanProperty raw = (BeanProperty) property;
              raw.set(embeddedId, conversionService.convertRequired(storedValue, property.asArgument()));
            }
          }
        }

        if (embeddedId == null) {
          Document embeddedIdDoc = Document.createDocument();
          for (BeanProperty<?, ?> property : idIntrospection.getBeanProperties()) {
            String storedName = property.getAnnotationMetadata()
                .stringValue(MappedProperty.class)
                .filter(v -> !v.isBlank())
                .orElse(property.getName());
            Object storedValue = doc.get(storedName);
            if (storedValue != null) {
              embeddedIdDoc.put(property.getName(), storedValue);
            }
          }
          embeddedId = nitriteMapper.tryConvert(embeddedIdDoc, embeddedIdType);
        }
        if (embeddedId != null) {
          idProp.getProperty().set(entity, embeddedId);
        }
      } catch (Exception ignored) {
      }
    }
    return entity;
  }

  /** Convert a stored id value (e.g. String from Jackson) to the entity's id type. */
  private static Object convertIdValue(final Object stored, final Class<?> targetType) {
    if (targetType == UUID.class && stored instanceof String) {
      return UUID.fromString((String) stored);
    }
    return stored;
  }

  /**
   * Normalize a field name from SQL WHERE clause to Nitrite storage field name. Entities
   * with @MappedProperty("_id") generate SQL with "_id" but we store as "id".
   */
  private static String normalizeFieldName(final String field) {
    return "_id".equals(field) ? "id" : field;
  }

  /**
   * Normalize a value for use in a Nitrite filter. Jackson serializes UUID fields as strings, so
   * UUID values must be converted to String before comparison.
   */
  private static Object toFilterValue(final Object val) {
    if (val instanceof UUID) {
      return val.toString();
    }
    if (val instanceof Instant instant) {
      // Match the mapping used by the Nitrite Jackson mapper in tests: store/query Instants as an
      // epoch-second double (keeps equality and ordering comparisons consistent).
      return instant.getEpochSecond() + instant.getNano() / 1_000_000_000.0;
    }
    return val;
  }

  /**
   * Normalize a query parameter for use in Nitrite filters, including Micronaut Data embedded-id
   * values (which may appear as a single parameter in SQL where clauses).
   */
  private Object toNitriteFilterValue(final Object val) {
    Object normalized = toFilterValue(val);
    if (normalized == null) {
      return null;
    }
    if (normalized.getClass().isAnnotationPresent(Embeddable.class)) {
      Object converted = nitriteMapper.tryConvert(normalized, Document.class);
      if (converted instanceof Document doc) {
        for (String field : doc.getFields()) {
          doc.put(field, toFilterValue(doc.get(field)));
        }
        return doc;
      }
    }
    return normalized;
  }

  /**
   * Build an equality filter that tolerates numeric representation differences introduced by the
   * mapping layer (e.g. stored as {@code Long} vs {@code BigDecimal}, or {@code Double} vs
   * {@code BigDecimal}).
   */
  private static Filter eqWithNumericCoercion(final String field, final Object value) {
    Filter base = FluentFilter.where(field).eq(value);
    if (!(value instanceof Number n) || value == null) {
      return base;
    }

    List<Filter> filters = new ArrayList<>();
    filters.add(base);

    // Also try BigDecimal representation (Nitrite/Jackson can store numbers this way).
    try {
      java.math.BigDecimal asBigDecimal = new java.math.BigDecimal(n.toString());
      filters.add(FluentFilter.where(field).eq(asBigDecimal));

      // If the number is a whole number, also try integral representations.
      if (asBigDecimal.stripTrailingZeros().scale() <= 0) {
        long asLong = asBigDecimal.longValue();
        filters.add(FluentFilter.where(field).eq(asLong));
        if (asLong >= Integer.MIN_VALUE && asLong <= Integer.MAX_VALUE) {
          filters.add(FluentFilter.where(field).eq((int) asLong));
        }
      } else {
        // Non-integer: try double representation too.
        filters.add(FluentFilter.where(field).eq(asBigDecimal.doubleValue()));
      }
    } catch (Exception ignored) {
      // Keep base only
    }

    if (filters.size() == 1) {
      return base;
    }
    return Filter.or(filters.toArray(new Filter[0]));
  }

  /**
   * Generate and set ID on entity if @GeneratedValue is present. Supports String (UUID), Long
   * (timestamp-based), and Integer IDs.
   */
  private <T> void generateIdIfNecessary(final T entity, final Class<T> type) {
    RuntimePersistentEntity<T> persistentEntity = getEntity(type);
    var idProperty = persistentEntity.getIdentity();
    if (idProperty != null && idProperty.isAnnotationPresent(GeneratedValue.class)) {
      Class<?> idType = idProperty.getType();
      Object generatedId;

      if (idType == String.class) {
        generatedId = UUID.randomUUID().toString();
      } else if (idType == UUID.class) {
        generatedId = UUID.randomUUID();
      } else if (idType == Long.class || idType == long.class) {
        generatedId = System.currentTimeMillis();
      } else if (idType == Integer.class || idType == int.class) {
        generatedId = (int) (System.currentTimeMillis() % Integer.MAX_VALUE);
      } else {
        // Default to UUID string for unknown types
        generatedId = UUID.randomUUID().toString();
      }

      idProperty.getProperty().set(entity, generatedId);
    }
  }

  // ========== Core CRUD Operations ==========

  /**
   * Build an ID filter for the given entity type.
   *
   * <p>Nitrite stores user IDs in regular document fields (not in Nitrite's internal {@code _id}).
   * For typical entities this is {@code id}, but for {@link EmbeddedId} it is the embedded property
   * name (e.g. {@code projectId}).
   */
  private <T> Filter idEqualsFilter(final Class<T> type, final Object id) {
    RuntimePersistentEntity<T> persistentEntity = getEntity(type);
    RuntimePersistentProperty idProperty = persistentEntity.getIdentity();
    String idField = "id";
    if (idProperty != null) {
      try {
        idField = normalizeFieldName(idProperty.getName());
      } catch (Exception ignored) {
        // Fall back to "id"
      }
    }

    if (idProperty != null && idProperty.isAnnotationPresent(EmbeddedId.class) && id != null) {
      try {
        Document idDoc = (Document) nitriteMapper.tryConvert(id, Document.class);
        List<Filter> parts = new ArrayList<>();
        for (String field : idDoc.getFields()) {
          parts.add(eqWithNumericCoercion(field, toFilterValue(idDoc.get(field))));
        }
        if (parts.isEmpty()) {
          return Filter.ALL;
        }
        if (parts.size() == 1) {
          return parts.get(0);
        }
        return Filter.and(parts.toArray(new Filter[0]));
      } catch (Exception ignored) {
        return FluentFilter.where(idField).eq(id);
      }
    }

    return eqWithNumericCoercion(idField, toFilterValue(id));
  }

  /** Read the entity ID value using the runtime entity metadata. */
  private <T> Object getEntityIdValue(final T entity, final Class<T> type) {
    RuntimePersistentEntity<T> persistentEntity = getEntity(type);
    RuntimePersistentProperty idProperty = persistentEntity.getIdentity();
    if (idProperty == null) {
      return null;
    }
    return idProperty.getProperty().get(entity);
  }

  @Override
  public <T> T findOne(final Class<T> type, final Object id) {
    NitriteCollection collection = getCollection(type);
    Document doc = collection.find(idEqualsFilter(type, id)).firstOrNull();
    if (doc == null) {
      return null;
    }
    return fromDocument(doc, type);
  }

  @Override
  public <T> T persist(@NonNull final InsertOperation<T> operation) {
    T entity = operation.getEntity();
    Class<T> type = operation.getRootEntity();
    generateIdIfNecessary(entity, type);
    NitriteCollection collection = getCollection(type);
    Document doc = toDocument(entity);
    collection.insert(doc);
    return entity;
  }

  @Override
  public <T> Iterable<T> persistAll(@NonNull final InsertBatchOperation<T> operation) {
    Class<T> type = operation.getRootEntity();
    NitriteCollection collection = getCollection(type);
    for (T entity : operation) {
      generateIdIfNecessary(entity, type);
      collection.insert(toDocument(entity));
    }
    return operation;
  }

  @Override
  public <T> T update(@NonNull final UpdateOperation<T> operation) {
    T entity = operation.getEntity();
    Class<T> type = operation.getRootEntity();
    NitriteCollection collection = getCollection(type);
    Document doc = toDocument(entity);
    Object idValue = getEntityIdValue(entity, type);
    if (idValue != null) {
      collection.update(idEqualsFilter(type, idValue), doc);
    }
    // Nitrite doesn't modify documents server-side, so return entity directly
    return entity;
  }

  @Override
  public <T> Iterable<T> updateAll(@NonNull final UpdateBatchOperation<T> operation) {
    Class<T> type = operation.getRootEntity();
    NitriteCollection collection = getCollection(type);
    for (T entity : operation) {
      Document doc = toDocument(entity);
      Object idValue = getEntityIdValue(entity, type);
      if (idValue != null) {
        collection.update(idEqualsFilter(type, idValue), doc);
      }
    }
    return operation;
  }

  @Override
  public <T> int delete(@NonNull final DeleteOperation<T> operation) {
    Class<T> type = operation.getRootEntity();
    NitriteCollection collection = getCollection(type);
    T entity = operation.getEntity();
    Object idValue = getEntityIdValue(entity, type);
    if (idValue == null) {
      return 0;
    }
    var result = collection.remove(idEqualsFilter(type, idValue), false);
    return result.getAffectedCount();
  }

  @Override
  public <T> Optional<Number> deleteAll(@NonNull final DeleteBatchOperation<T> operation) {
    Class<T> type = operation.getRootEntity();
    NitriteCollection collection = getCollection(type);

    // Check if this is a "delete all" operation (no specific entities)
    if (operation.all()) {
      collection.clear();
      return Optional.of(-1); // Nitrite clear() doesn't return count easily, -1 signals success
    }

    // Delete specific entities by ID
    // Move getEntity() outside the loop (registry lookup returns same object)
    RuntimePersistentEntity<T> persistentEntity =
        (RuntimePersistentEntity<T>) runtimeEntityRegistry.getEntity(type);
    RuntimePersistentProperty idProperty = persistentEntity.getIdentity();
    int count = 0;
    for (T entity : operation) {
      if (idProperty != null) {
        Object idValue = idProperty.getProperty().get(entity);
        if (idValue != null) {
          var result = collection.remove(idEqualsFilter(type, idValue), false);
              // Note: keep ID comparisons flexible for numeric IDs, as Nitrite/Jackson may store
              // them as either integral types or BigDecimal depending on the conversion path.
          if (result.getAffectedCount() > 0) {
            count++;
          }
        }
      }
    }
    return Optional.of(count);
  }

  /** Build FindOptions with pagination and sorting. */
  private FindOptions buildFindOptions(final Pageable pageable, final String jsonQuery) {
    FindOptions options = buildFindOptions(pageable, (Sort) null);
    if (jsonQuery != null && jsonQuery.contains("\"$skip\"")) {
      try {
        Object parsed = parseJson(jsonQuery);
        if (parsed instanceof Map m) {
          if (m.get("$skip") instanceof Number n) {
            options.skip(n.longValue());
          }
          if (m.get("$limit") instanceof Number n) {
            options.limit(n.intValue());
          }
        }
      } catch (Exception ignored) {
        // Ignore pagination hints parsing errors; fall back to Pageable-only options.
      }
    }
    return options;
  }

  /** Build FindOptions with pagination and sorting, merging additional sort from QueryModel. */
  private FindOptions buildFindOptions(final Pageable pageable, final Sort additionalSort) {
    FindOptions options = new FindOptions();

    // Pagination
    long offset = pageable.getOffset();
    if (offset > 0) {
      options.skip(offset);
    }
    int size = pageable.getSize();
    if (size > 0) {
      options.limit(size);
    }

    // Sorting - pageable sort takes precedence over method-name OrderBy.
    // Micronaut Data merges them into pageable.getSort(), but the order matters.
    // We want the most specific sort (from Pageable argument) to win.
    Map<String, Sort.Order> mergedOrders = new LinkedHashMap<>();

    // 1. Apply additionalSort (from method name OrderBy)
    if (additionalSort != null && additionalSort.isSorted()) {
      for (var order : additionalSort.getOrderBy()) {
        mergedOrders.put(order.getProperty(), order);
      }
    }

    // 2. Apply pageable sort (overwrites same fields from method name)
    if (pageable.getSort() != null && pageable.getSort().isSorted()) {
      for (var order : pageable.getSort().getOrderBy()) {
        mergedOrders.put(order.getProperty(), order);
      }
    }

    if (!mergedOrders.isEmpty()) {
      for (var order : mergedOrders.values()) {
        String field = normalizeFieldName(order.getProperty());
        SortOrder sortOrder =
            order.getDirection() == Sort.Order.Direction.ASC
                ? SortOrder.Ascending
                : SortOrder.Descending;
        options.thenOrderBy(field, sortOrder);
      }
    }

    return options;
  }

  /** Parses sort from SQL ORDER BY clause. Format: alias.field1 ASC, alias.field2 DESC */
  private Sort parseSortFromSqlQuery(final String sql) {
    if (sql == null) {
      return null;
    }
    int idx = sql.toUpperCase().indexOf(" ORDER BY ");
    if (idx < 0) {
      return null;
    }
    String clause = sql.substring(idx + 10).trim();
    List<Sort.Order> orders = new ArrayList<>();
    for (String part : clause.split(",")) {
      String[] tokens = part.trim().split("\\s+");
      if (tokens.length == 0 || tokens[0].isBlank()) {
        continue;
      }
      String fieldExpr = tokens[0];
      String field =
          fieldExpr.contains(".") ? fieldExpr.substring(fieldExpr.lastIndexOf('.') + 1) : fieldExpr;
      boolean desc = tokens.length > 1 && "DESC".equalsIgnoreCase(tokens[1]);
      orders.add(desc ? Sort.Order.desc(field) : Sort.Order.asc(field));
    }
    return orders.isEmpty() ? null : Sort.of(orders);
  }

  /** Parses sort from a JSON query string's $sort key (embedded by NitriteQueryBuilder). */
  @SuppressWarnings("unchecked")
  private Sort parseSortFromJsonQuery(final String queryString) {
    if (queryString == null || !queryString.contains("\"$sort\"")) {
      return null;
    }
    try {
      Object parsed = parseJson(queryString);
      if (parsed instanceof Map) {
        Object sortObj = ((Map<String, Object>) parsed).get("$sort");
        if (sortObj instanceof Map) {
          List<Sort.Order> orders = new ArrayList<>();
          for (Map.Entry<?, ?> e : ((Map<?, ?>) sortObj).entrySet()) {
            String field = e.getKey().toString();
            int dir = e.getValue() instanceof Number ? ((Number) e.getValue()).intValue() : 1;
            orders.add(dir >= 1 ? Sort.Order.asc(field) : Sort.Order.desc(field));
          }
          return orders.isEmpty() ? null : Sort.of(orders);
        }
      }
    } catch (Exception ignored) {
    }
    return null;
  }

  /** Parse sort string from query hints (format: "field1:ASC,field2:DESC"). */
  private Sort parseSortFromHints(final Map<String, Object> hints) {
    if (hints == null || hints.isEmpty()) {
      return null;
    }

    Object sortObj = hints.get("sort");
    if (sortObj instanceof String sortStr && !sortStr.isEmpty()) {
      List<Sort.Order> orders = new ArrayList<>();
      for (String part : sortStr.split(",")) {
        String[] parts = part.trim().split(":");
        if (parts.length == 2) {
          String field = parts[0];
          Sort.Order.Direction direction = Sort.Order.Direction.valueOf(parts[1]);
          if (direction == Sort.Order.Direction.ASC) {
            orders.add(Sort.Order.asc(field));
          } else {
            orders.add(Sort.Order.desc(field));
          }
        }
      }
      if (!orders.isEmpty()) {
        return Sort.of(orders);
      }
    }
    return null;
  }

  @Override
  public <T> Iterable<T> findAll(@NonNull final PagedQuery<T> query) {
    Class<T> type = (Class<T>) query.getRootEntity();
    NitriteCollection collection = getCollection(type);

    // Build options with pagination and sorting
    FindOptions options = buildFindOptions(query.getPageable(), (String) null);

    var cursor = collection.find(Filter.ALL, options);
    List<T> results = new ArrayList<>();
    for (Document doc : cursor) {
      results.add(fromDocument(doc, type));
    }
    return results;
  }

  @Override
  public <T> long count(@NonNull final PagedQuery<T> query) {
    Class<T> type = (Class<T>) query.getRootEntity();
    NitriteCollection collection = getCollection(type);
    return collection.size();
  }

